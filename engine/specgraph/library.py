"""模块库：可拖进画布的契约骨架，以及「用户中心」示例。

这里只有文本模板，没有任何实现。模板是**起点**：拖进去之后契约就归这个模块自己，
改它、删它、加约束都由人决定。复用别人的模块仍然要用「引用外部契约」（[[ref]]），
不是把文本拷过来——拷贝会立刻分叉成两份真相。
"""

from __future__ import annotations

from dataclasses import dataclass

SEC_E = "提供"
SEC_N = "需要"
SEC_C = "约束"


@dataclass(frozen=True)
class Template:
    key: str
    name: str
    blurb: str
    body: str          # 三段式正文，{name} 会被替换成实际模块名
    node_type: str = "module"   # 纯展示的类型标签（见 model.TYPES）


def _spec(name: str, body: str, node_type: str = "") -> str:
    head = f"---\nname: {name}\nkind: module\n"
    if node_type:
        head += f"type: {node_type}\n"
    return head + "---\n\n" + body.strip() + "\n"


