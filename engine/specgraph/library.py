def catalog() -> list[dict]:
    from .model import type_family, type_label
    return [{"key": t.key, "name": t.name, "blurb": t.blurb,
             "type": t.node_type, "type_label": type_label(t.node_type),
             "family": type_family(t.node_type)}
            for t in TEMPLATES.values()]


def spec_text(key: str, name: str) -> str:
    t = TEMPLATES[key]
    return _spec(name, t.body, t.node_type)


